//! UDP payload database (`nmap-payloads`). Mapping: UDP port → bytes to send
//! so the target's service responds. Built from the upstream nmap-payloads
//! file, transcribed to literal byte arrays.

/// Returns the bytes to send when probing this UDP port, or `None` if a
/// generic empty payload should be used.
pub fn for_port(port: u16) -> Option<&'static [u8]> {
    Some(match port {
        53 => &DNS_QUERY,
        67 | 68 => &DHCP_DISCOVER,
        69 => &TFTP_READ,
        111 => &RPC_DUMP,
        123 => &NTP_REQUEST,
        137 => &NETBIOS_NAME_QUERY,
        161 => &SNMP_GETREQ,
        177 => &XDMCP_QUERY,
        500 => &ISAKMP_MAIN_MODE,
        520 => &RIP_REQUEST,
        623 => &ASF_PING,
        1194 => &OPENVPN_HELLO,
        1434 => &MSSQL_PING,
        1900 => &SSDP_MSEARCH,
        3702 => &WS_DISCOVERY,
        4500 => &ISAKMP_NAT,
        5060 => &SIP_OPTIONS,
        5353 => &MDNS_QUERY,
        5683 => &COAP_GET,
        17185 => &VXWORKS_WDB,
        27015 => &SRCDS_INFO,
        27960 => &Q3_GETSTATUS,
        47808 => &BACNET_WHO_IS,
        _ => return None,
    })
}

